"""Single-file bundler for W1bbexHub.py from modular src/ modules."""

from __future__ import annotations

import ast
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
SRC_DIR = HERE / "src"
OUT_FILE = HERE.parent.parent / "W1bbexHub.py"
BUNDLE_PKG = "_w1bbex_hub_src"


def _format_source_literal(source: str) -> str:
    """Serialize module source cleanly as a parenthesized multi-line string literal."""
    if not source:
        return '""'
    rendered = "\n".join(f"        {line!r}" for line in source.splitlines(keepends=True))
    return f"(\n{rendered}\n    )"


def _collect_sources(src_dir: Path) -> dict[str, str]:
    """Read, validate syntax, and order modules under src_dir."""
    if not (src_dir / "__init__.py").is_file():
        raise FileNotFoundError(f"Missing package initializer: {src_dir / '__init__.py'}")
    if not (src_dir / "plugin.py").is_file():
        raise FileNotFoundError(f"Missing plugin entry module: {src_dir / 'plugin.py'}")

    files = sorted(
        (p for p in src_dir.rglob("*.py") if p.is_file() and "__pycache__" not in p.parts),
        key=lambda p: (len(p.relative_to(src_dir).parts), p.stem != "__init__", p.relative_to(src_dir).as_posix()),
    )

    sources: dict[str, str] = {}
    for path in files:
        rel = path.relative_to(src_dir)
        key = ".".join(rel.with_suffix("").parts)
        text = path.read_text(encoding="utf-8")
        ast.parse(text, filename=str(path))
        sources[key] = text
    return sources


def _read_runtime_metadata(src_dir: Path) -> dict[str, object]:
    """Read top-level Cardinal metadata constants from src/runtime.py via AST."""
    runtime_src = (src_dir / "runtime.py").read_text(encoding="utf-8")
    tree = ast.parse(runtime_src, filename=str(src_dir / "runtime.py"))
    want = {"NAME", "VERSION", "DESCRIPTION", "CREDITS", "PLUGIN_ID", "SETTINGS_PAGE", "UUID", "COMMANDS"}
    meta: dict[str, object] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            key = node.targets[0].id
            if key in want:
                meta[key] = ast.literal_eval(node.value)
    missing = want - set(meta)
    if missing:
        raise ValueError(f"Missing metadata constants in runtime.py: {sorted(missing)}")
    return meta


def _render_bundle(sources: dict[str, str], meta: dict[str, object]) -> str:
    """Render standalone single-file W1bbexHub.py with top-level Cardinal metadata."""
    entries = "\n".join(f"    {name!r}: {_format_source_literal(code)}," for name, code in sources.items())
    return (
        "# W1bbexHub bundled single-file plugin (generated by plugins/w1bbex-hub/build.py).\n"
        "# Edit modular files under plugins/w1bbex-hub/src/ and re-run build.py.\n\n"
        "from __future__ import annotations\n\n"
        "import importlib\n"
        "import importlib.abc\n"
        "import importlib.util\n"
        "from pathlib import Path\n"
        "import sys\n\n"
        f"NAME = {meta['NAME']!r}\n"
        f"VERSION = {meta['VERSION']!r}\n"
        f"DESCRIPTION = {meta['DESCRIPTION']!r}\n"
        f"CREDITS = {meta['CREDITS']!r}\n"
        f"PLUGIN_ID = {meta['PLUGIN_ID']!r}\n"
        f"SETTINGS_PAGE = {meta['SETTINGS_PAGE']!r}\n"
        f"UUID = {meta['UUID']!r}\n"
        f"COMMANDS = {meta['COMMANDS']!r}\n\n"
        f"_BUNDLE_PKG = {BUNDLE_PKG!r}\n"
        "_ENTRY_FILE = str(Path(__file__).resolve())\n\n"
        "_BUNDLE_SOURCES: dict[str, str] = {\n"
        f"{entries}\n"
        "}\n\n\n"
        "class _W1bbexHubLoader(importlib.abc.Loader):\n"
        '    """Execute a bundled source module inside its isolated virtual package."""\n\n'
        "    def __init__(self, mod_name: str, source: str, is_pkg: bool) -> None:\n"
        "        self._mod_name = mod_name\n"
        "        self._source = source\n"
        "        self._is_pkg = is_pkg\n\n"
        "    def create_module(self, spec):\n"
        "        return None\n\n"
        "    def exec_module(self, module) -> None:\n"
        "        module.__file__ = _ENTRY_FILE\n"
        "        if self._is_pkg:\n"
        "            module.__path__ = []\n"
        "            module.__package__ = module.__name__\n"
        "        else:\n"
        '            module.__package__ = module.__name__.rpartition(".")[0]\n'
        '        filename = f"{_ENTRY_FILE}::<{_BUNDLE_PKG}.{self._mod_name}>"\n'
        '        code = compile(self._source, filename, "exec")\n'
        "        exec(code, module.__dict__)\n\n\n"
        "class _W1bbexHubFinder(importlib.abc.MetaPathFinder):\n"
        '    """Resolve imports for the virtual _w1bbex_hub_src package tree."""\n\n'
        "    _bundle_id = _BUNDLE_PKG\n\n"
        "    def find_spec(self, fullname: str, path=None, target=None):\n"
        "        if fullname == _BUNDLE_PKG:\n"
        '            mod_key = "__init__"\n'
        "            is_pkg = True\n"
        '        elif fullname.startswith(f"{_BUNDLE_PKG}."):\n'
        "            sub_name = fullname[len(_BUNDLE_PKG) + 1:]\n"
        '            pkg_key = f"{sub_name}.__init__"\n'
        "            if pkg_key in _BUNDLE_SOURCES:\n"
        "                mod_key = pkg_key\n"
        "                is_pkg = True\n"
        "            elif sub_name in _BUNDLE_SOURCES:\n"
        "                mod_key = sub_name\n"
        "                is_pkg = False\n"
        "            else:\n"
        "                return None\n"
        "        else:\n"
        "            return None\n"
        "        source = _BUNDLE_SOURCES.get(mod_key)\n"
        "        if source is None:\n"
        "            return None\n"
        "        loader = _W1bbexHubLoader(mod_key, source, is_pkg)\n"
        "        return importlib.util.spec_from_loader(fullname, loader, origin=_ENTRY_FILE, is_package=is_pkg)\n\n\n"
        "def _bootstrap_bundle():\n"
        '    """Reset prior bundled state and load _w1bbex_hub_src.plugin."""\n'
        "    sys.meta_path[:] = [f for f in sys.meta_path if getattr(f, '_bundle_id', None) != _BUNDLE_PKG]\n"
        '    prefix = f"{_BUNDLE_PKG}."\n'
        "    for name in list(sys.modules):\n"
        "        if name == _BUNDLE_PKG or name.startswith(prefix):\n"
        "            sys.modules.pop(name, None)\n"
        "    sys.meta_path.insert(0, _W1bbexHubFinder())\n"
        '    return importlib.import_module(f"{_BUNDLE_PKG}.plugin")\n\n\n'
        "_entry_mod = _bootstrap_bundle()\n"
        "custom_init = _entry_mod.custom_init\n"
        "post_init_cardinal = _entry_mod.post_init_cardinal\n"
        "init_cardinal = _entry_mod.init_cardinal\n"
        "BIND_TO_PRE_INIT = _entry_mod.BIND_TO_PRE_INIT\n"
        "BIND_TO_POST_INIT = _entry_mod.BIND_TO_POST_INIT\n"
        "BIND_TO_NEW_MESSAGE = _entry_mod.BIND_TO_NEW_MESSAGE\n"
        "BIND_TO_DELETE = _entry_mod.BIND_TO_DELETE\n"
    )


def build(out_file: Path | None = None) -> Path:
    """Build standalone W1bbexHub.py from src modules and verify its syntax."""
    target = Path(out_file) if out_file else OUT_FILE
    sources = _collect_sources(SRC_DIR)
    meta = _read_runtime_metadata(SRC_DIR)
    rendered = _render_bundle(sources, meta)
    ast.parse(rendered, filename=str(target))
    target.write_text(rendered, encoding="utf-8", newline="\n")
    return target


if __name__ == "__main__":
    built = build()
    sys.stdout.write(f"Built {built}\n")
