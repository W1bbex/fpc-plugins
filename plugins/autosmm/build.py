"""Single-file bundler for the modular AutoSMM plugin."""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC_DIR = ROOT / "src"
OUT_FILE = ROOT / "AutoSMM.py"
BUNDLE_PKG = "_autosmm_src"


def _format_source_literal(source: str) -> str:
    """Serialize module source into a parenthesized multi-line string literal."""
    if not source:
        return '""'
    lines = source.splitlines(keepends=True)
    rendered = "\n".join(f"        {line!r}" for line in lines)
    return f"(\n{rendered}\n    )"


def _collect_sources(src_dir: Path) -> dict[str, str]:
    """Read and syntax-check all Python modules under src_dir."""
    if not (src_dir / "__init__.py").is_file():
        raise FileNotFoundError(f"Missing package initializer: {src_dir / '__init__.py'}")
    if not (src_dir / "plugin.py").is_file():
        raise FileNotFoundError(f"Missing plugin entry module: {src_dir / 'plugin.py'}")

    candidates = [
        path for path in src_dir.rglob("*.py")
        if path.is_file() and "__pycache__" not in path.parts
    ]
    files = sorted(
        candidates,
        key=lambda path: (
            len(path.relative_to(src_dir).parts),
            path.stem != "__init__",
            path.relative_to(src_dir).as_posix(),
        ),
    )

    sources: dict[str, str] = {}
    for path in files:
        rel = path.relative_to(src_dir)
        if len(rel.parts) > 1 and not (path.parent / "__init__.py").is_file():
            raise FileNotFoundError(f"Missing subpackage initializer: {path.parent / '__init__.py'}")
        key = ".".join(rel.with_suffix("").parts)
        text = path.read_text(encoding="utf-8")
        ast.parse(text, filename=str(path))
        sources[key] = text
    return sources


def _read_runtime_metadata(src_dir: Path) -> dict[str, object]:
    """Read top-level Cardinal metadata constants from src/runtime.py via AST."""
    runtime_path = src_dir / "runtime.py"
    tree = ast.parse(runtime_path.read_text(encoding="utf-8"), filename=str(runtime_path))
    want = {"NAME", "VERSION", "DESCRIPTION", "CREDITS", "UUID", "SETTINGS_PAGE"}
    meta: dict[str, object] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            key = node.targets[0].id
            if key in want:
                meta[key] = ast.literal_eval(node.value)
    missing = want - set(meta)
    if missing:
        raise ValueError(f"Missing metadata constants in runtime.py: {sorted(missing)}")
    return meta


def _render_bundle(sources: dict[str, str], meta: dict[str, object]) -> str:
    """Render the standalone AutoSMM.py plugin bundle from src modules."""
    entries = "\n".join(
        f"    {name!r}: {_format_source_literal(code)},"
        for name, code in sources.items()
    )
    return (
        "# AutoSMM bundled plugin (generated by build.py from src/).\n"
        "# Do not edit generated bundle metadata manually; edit src/ modules and re-run build.py.\n"
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "import importlib\n"
        "import importlib.abc\n"
        "import importlib.util\n"
        "from pathlib import Path\n"
        "import sys\n"
        "\n"
        f"NAME = {meta['NAME']!r}\n"
        f"VERSION = {meta['VERSION']!r}\n"
        f"DESCRIPTION = {meta['DESCRIPTION']!r}\n"
        f"CREDITS = {meta['CREDITS']!r}\n"
        f"UUID = {meta['UUID']!r}\n"
        f"SETTINGS_PAGE = {meta['SETTINGS_PAGE']!r}\n"
        "\n"
        f"_BUNDLE_PKG = {BUNDLE_PKG!r}\n"
        "_ENTRY_FILE = str(Path(__file__).resolve())\n"
        "\n"
        "_BUNDLE_SOURCES: dict[str, str] = {\n"
        f"{entries}\n"
        "}\n"
        "\n"
        "\n"
        "class _AutoSMMLoader(importlib.abc.Loader):\n"
        '    """Execute a bundled source module inside its isolated virtual package."""\n'
        "\n"
        "    def __init__(self, mod_name: str, source: str, is_pkg: bool) -> None:\n"
        "        self._mod_name = mod_name\n"
        "        self._source = source\n"
        "        self._is_pkg = is_pkg\n"
        "\n"
        "    def create_module(self, spec):\n"
        "        return None\n"
        "\n"
        "    def exec_module(self, module) -> None:\n"
        "        module.__file__ = _ENTRY_FILE\n"
        "        if self._is_pkg:\n"
        "            module.__path__ = []\n"
        "            module.__package__ = module.__name__\n"
        "        else:\n"
        '            module.__package__ = module.__name__.rpartition(".")[0]\n'
        '        filename = f"{_ENTRY_FILE}::<{_BUNDLE_PKG}.{self._mod_name}>"\n'
        '        code = compile(self._source, filename, "exec")\n'
        "        exec(code, module.__dict__)\n"
        "\n"
        "\n"
        "class _AutoSMMFinder(importlib.abc.MetaPathFinder):\n"
        '    """Resolve imports for the virtual _autosmm_src package tree."""\n'
        "\n"
        "    _autosmm_bundle_id = _BUNDLE_PKG\n"
        "\n"
        "    def find_spec(self, fullname: str, path=None, target=None):\n"
        "        if fullname == _BUNDLE_PKG:\n"
        '            mod_key = "__init__"\n'
        "            is_pkg = True\n"
        '        elif fullname.startswith(f"{_BUNDLE_PKG}."):\n'
        "            sub_name = fullname[len(_BUNDLE_PKG) + 1:]\n"
        '            pkg_key = f"{sub_name}.__init__"\n'
        "            if pkg_key in _BUNDLE_SOURCES:\n"
        "                mod_key = pkg_key\n"
        "                is_pkg = True\n"
        "            elif sub_name in _BUNDLE_SOURCES:\n"
        "                mod_key = sub_name\n"
        "                is_pkg = False\n"
        "            else:\n"
        "                return None\n"
        "        else:\n"
        "            return None\n"
        "        source = _BUNDLE_SOURCES.get(mod_key)\n"
        "        if source is None:\n"
        "            return None\n"
        "        loader = _AutoSMMLoader(mod_key, source, is_pkg)\n"
        "        return importlib.util.spec_from_loader(\n"
        "            fullname,\n"
        "            loader,\n"
        "            origin=_ENTRY_FILE,\n"
        "            is_package=is_pkg,\n"
        "        )\n"
        "\n"
        "\n"
        "def _bootstrap_bundle():\n"
        '    """Reset any prior _autosmm_src state and load _autosmm_src.plugin."""\n'
        "    sys.meta_path[:] = [\n"
        "        finder\n"
        "        for finder in sys.meta_path\n"
        '        if getattr(finder, "_autosmm_bundle_id", None) != _BUNDLE_PKG\n'
        "    ]\n"
        '    prefix = f"{_BUNDLE_PKG}."\n'
        "    for name in list(sys.modules):\n"
        "        if name == _BUNDLE_PKG or name.startswith(prefix):\n"
        "            sys.modules.pop(name, None)\n"
        "    sys.meta_path.insert(0, _AutoSMMFinder())\n"
        '    return importlib.import_module(f"{_BUNDLE_PKG}.plugin")\n'
        "\n"
        "\n"
        "_entry_mod = _bootstrap_bundle()\n"
        "for _attr in dir(_entry_mod):\n"
        '    if not (_attr.startswith("__") and _attr.endswith("__")):\n'
        "        globals()[_attr] = getattr(_entry_mod, _attr)\n"
        "del _attr\n"
    )


def build() -> Path:
    """Build single-file AutoSMM.py from src modules and verify its syntax."""
    sources = _collect_sources(SRC_DIR)
    meta = _read_runtime_metadata(SRC_DIR)
    rendered = _render_bundle(sources, meta)
    ast.parse(rendered, filename=str(OUT_FILE))
    OUT_FILE.write_text(rendered, encoding="utf-8")
    return OUT_FILE


if __name__ == "__main__":
    build()
